/*
    Model Name: agg_customer_rfm
    
    Business Purpose:
    Consolidates sales transaction history at the CUSTOMER level to build 
    an RFM (Recency, Frequency, Monetary) segmentation mart 
    for Marketing and CRM.
    
    RFM Mapping & Logic:
    - Recency (R): Calculated via `last_order_date` and `days_since_last_order`.
    - Frequency (F): Calculated via `total_orders` (count of distinct order IDs).
    - Monetary (M): Calculated via `lifetime_value` (sum of net sales amount) 
                    and `average_ticket`.
    - Segmentation: Rule-based classification based on R, F, and M thresholds.
*/

-- ============================================================================
-- STEP 1: Sales Preparation (Sales Items + Dates)
-- Fetches raw transaction line items and joins with dim_dates 
-- to derive the actual order date.
-- ============================================================================
with sales_items as (
    select
        f.customer_sk
        , f.order_id
        , cast(d.full_date as date) as order_date  
        , f.net_sales_amount                           
    from {{ ref('fct_sales_items') }} as f
    left join {{ ref('dim_dates') }} as d
        on cast(f.date_sk as string) = cast(d.date_sk as string)
),

-- ============================================================================
-- STEP 2: Customer Descriptive Attributes
-- Retrieves customer demographic/geographic metadata for slicing and 
-- filtering in BI tools (e.g., segment analysis by State or Person Type).
-- ============================================================================
customers as (
    select
        customer_sk
        , person_type
        , primary_state
    from {{ ref('dim_customers') }}
),

-- ============================================================================
-- STEP 3: THE RFM CORE (Customer-level Aggregation)
-- Rollup from transaction-level granularity to 1 row per customer.
-- Computes raw RFM metrics using aggregation functions (MAX, COUNT, SUM).
-- ============================================================================
rfm_base as (
    select
        si.customer_sk
        , coalesce(c.person_type, 'N/A') as person_type
        , coalesce(c.primary_state, 'N/A') as primary_state
        
        ------------------------------------------------------------------------
        -- RECENCY (R) CORE:
        -- Identifies the most recent order date placed by the customer.
        ------------------------------------------------------------------------
        , max(si.order_date) as last_order_date
        
        ------------------------------------------------------------------------
        -- FREQUENCY (F) CORE:
        -- Counts total unique orders (order_id) placed over customer lifetime.
        ------------------------------------------------------------------------
        , count(distinct si.order_id) as total_orders
        
        ------------------------------------------------------------------------
        -- MONETARY (M) CORE:
        -- Sums total net revenue generated by customer over lifetime (LTV).
        ------------------------------------------------------------------------
        , sum(si.net_sales_amount) as lifetime_value

    from sales_items as si
    left join customers as c
        on si.customer_sk = c.customer_sk
    group by
        si.customer_sk
        , coalesce(c.person_type, 'N/A')
        , coalesce(c.primary_state, 'N/A')
),

-- ============================================================================
-- STEP 4: Derived RFM Metrics & Calculations
-- Converts raw dates and aggregated totals into actionable business KPIs.
-- ============================================================================
final_rfm as (
    select
        -- 1. Simple Attributes
        customer_sk
        , person_type
        , primary_state
        , last_order_date
        , total_orders                       -- (F) Final Frequency
        , lifetime_value                     -- (M) Final Total Monetary Value
        
        -- 2. Applied Calculations
        , current_date() as reference_date   -- Execution/Evaluation date
        
        ------------------------------------------------------------------------
        -- RECENCY (R) IN DAYS:
        -- Days elapsed between the execution date and customer's last order.
        ------------------------------------------------------------------------
        , datediff(current_date(), last_order_date) as days_since_last_order
        
        ------------------------------------------------------------------------
        -- MONETARY COMPLEMENT (AVERAGE TICKET):
        -- Average spend per order (LTV / Total Orders) protect division by zero.
        ------------------------------------------------------------------------
        , case
            when total_orders > 0 then lifetime_value / total_orders
            else 0
        end as average_ticket

    from rfm_base
)

-- ============================================================================
-- STEP 5: Final Output & Customer Classification
-- Selects final attributes, orders columns, and assigns RFM Segment logic.
-- ============================================================================
select
    customer_sk
    , person_type
    , primary_state
    , last_order_date
    , total_orders
    , lifetime_value
    , reference_date
    , days_since_last_order
    , average_ticket
    
    ----------------------------------------------------------------------------
    -- CUSTOMER SEGMENTATION (RFM Classification)
    -- Categorizes customers into strategic cohorts based on R, F, and M rules.
    ----------------------------------------------------------------------------
    , case
        when
            days_since_last_order <= 30
            and total_orders >= 5
            and lifetime_value >= 1000
            then 'VIP / Champion'
        when
            days_since_last_order <= 90 and total_orders >= 3
            then 'Loyal Customer'
        when
            days_since_last_order <= 30 and total_orders = 1
            then 'New Customer'
        when days_since_last_order > 90 and total_orders >= 2 then 'At Risk'
        when days_since_last_order > 180 then 'Hibernating / Churned'
        else 'Promising / Potential'
    end as customer_segment

from final_rfm